import type { Curriculum } from '../../src/engine/content/schema';

/** Renders docs/blueprint/02-curriculum.md from the compiled curriculum (single source of truth: content/). */
export function curriculumMarkdown(c: Curriculum): string {
  const L: string[] = [];
  const w = (s = '') => L.push(s);
  const lv = new Map(c.levels.map((l) => [l.id, l]));
  const st = new Map(c.stages.map((s) => [s.id, s]));
  const wd = new Map(c.worlds.map((x) => [x.id, x]));
  const s = c.stats;

  w('# 02 — Curriculum');
  w();
  w('> Persona: **Learning Scientist / CS Professor**. Generated by `npm run content:doc` from [`content/`](../../content/) — edit the YAML files, never this page.');
  w();
  w('## Totals (validated)');
  w();
  w('| Worlds | Stages | Levels | Core Path levels | Bonus levels | Prerequisites | Cross-stage | Stars available |');
  w('|---|---|---|---|---|---|---|---|');
  w(`| ${s.worlds} | ${s.stages} | ${s.levels} | ${s.coreLevels} | ${s.levels - s.coreLevels} | ${s.edges} | ${s.crossStageEdges} | ${s.maxStars.toLocaleString('en-US')} |`);
  w();
  w('## Rules');
  w();
  w('| Rule | Decision |');
  w('|---|---|');
  w('| Structure | World (domain) → Stage (subject) → Unit → Level (topic). One folder per world, one folder per stage — subjects are never mixed |');
  w('| Level clear | A level is **Cleared** only when its **level test** (built only from that level’s lesson) is passed with ≥ 70 %; ≥ 90 % gives the 2nd star; a spaced review test ≥ 3 days later gives the 3rd |');
  w('| Unlock | A level unlocks when every level in its `requires` list is Cleared |');
  w('| Road | Core levels are numbered 1, 2, 3… on the stage road in file order (prerequisites first) |');
  w('| Bonus | Non-core levels are bonus chests on a side trail from their host road level |');
  w('| Stage boss | Unlocks when every core level of the stage is Cleared; a stage test across all its levels |');
  w('| Core Path | Core levels depend only on core levels of the same or an earlier stage, so a beginner is never blocked |');
  w();
  w('## Worlds');
  w();
  w('| # | World | Biome | Stages | Levels |');
  w('|---|---|---|---|---|');
  for (const x of c.worlds) w(`| ${x.order} | **${x.title}** — ${x.tagline} | ${x.biome} | ${x.stageIds.map((i) => st.get(i)!.title).join(', ')} | ${x.levelCount} |`);
  w();
  w('## Core Path (stage order for a complete beginner)');
  w();
  w('| Step | Stage | World | Tier | Core levels | All levels |');
  w('|---|---|---|---|---|---|');
  c.corePath.forEach((id, i) => {
    const x = st.get(id)!;
    w(`| ${i + 1} | ${x.title} | ${wd.get(x.worldId)!.title} | ${x.tier} | ${x.coreLevelCount} | ${x.levelCount} |`);
  });
  w();
  for (const x of c.worlds) {
    w(`## World ${x.order} · ${x.title} — ${x.biome}`);
    w();
    for (const sid of x.stageIds) {
      const sg = st.get(sid)!;
      w(`### Stage ${x.order}-${sg.order} · ${sg.title}  ·  tier ${sg.tier}  ·  ${sg.levelCount} levels`);
      w();
      w(`**Boss — ${sg.boss.title}:** ${sg.boss.description}  `);
      w(`**Sources:** ${sg.refs.join('; ')}`);
      w();
      for (const u of sg.units) {
        w(`**${u.title}**`);
        w();
        w('| # | Level | Requires |');
        w('|---|---|---|');
        for (const id of u.levelIds) {
          const l = lv.get(id)!;
          const req = l.requires.map((r) => (lv.get(r)!.stageId === sid ? `\`${r}\`` : `*\`${r}\`* (${st.get(lv.get(r)!.stageId)!.title})`)).join(', ') || '—';
          w(`| ${l.number ?? 'Bonus'} | ${l.title} \`${l.id}\` | ${req} |`);
        }
        w();
      }
    }
  }
  return L.join('\n');
}
